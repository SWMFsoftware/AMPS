#!/usr/bin/env python3
"""Canonicalize candidate SR-NIEL proton/He-4 tables for InGaAs.

The target is the material-library alloy Ga0.47In0.53As at 300 K.  The
stoichiometry and density therefore come from the named material record, while
the displacement thresholds are taken from the open accepted manuscript of
Beaumel et al., ``Displacement Damage Effects in InGaAs Photodiodes due to
Electron, Proton, and Neutron Irradiations`` (IEEE TNS, 2020,
doi:10.1109/TNS.2020.2984133): 15 eV for In and 10 eV for both Ga and As.

The saved result pages must have been generated by SR-NIEL-7 v11.1 with its
predefined In_x Ga_(1-x) As compound, x=0.53, hadronic plus Coulomb terms, and
no threshold scaling.  This tool validates those choices before copying raw
evidence or emitting canonical CSV.  It does not generate neutron data or a
1-MeV-neutron-equivalent convention because the paper does not publish a
machine-readable neutron response table or standardized denominator.

Generated files are candidate reference data.  This script does not enable a
production response or claim that NIEL predicts every InGaAs device response.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import shutil
import sys


SCRIPT_DIR = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(SCRIPT_DIR))
from generate_stage5_niel_tables import parse_response  # noqa: E402


def sha256(path: pathlib.Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def require_page(path: pathlib.Path, required_text: list[str]) -> None:
    text = path.read_text(encoding="latin-1")
    missing = [token for token in required_text if token not in text]
    if missing:
        raise RuntimeError(f"{path} does not document required parameters: {missing}")


def write_charged(path: pathlib.Path, rows: list[tuple[float, float]],
                  expected_count: int) -> tuple[float, float]:
    positive = [(energy, niel) for energy, niel in rows if niel > 0.0]
    if len(positive) != expected_count:
        raise RuntimeError(
            f"{path.name}: expected {expected_count} positive nodes, found {len(positive)}"
        )
    lines = ["energy_MeV,niel_MeV_cm2_g"]
    lines.extend(f"{energy:.12e},{niel:.12e}" for energy, niel in positive)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return positive[0][0], positive[-1][0]


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--proton-html", type=pathlib.Path, required=True)
    parser.add_argument("--alpha-html", type=pathlib.Path, required=True)
    parser.add_argument("--output", type=pathlib.Path, required=True)
    args = parser.parse_args()

    # The order is In, Ga, As because that is the order printed by the
    # predefined SR-NIEL In_x Ga_(1-x) As compound form.
    common = ["15.00; 10.00; 10.00", "Hadron+Coulomb", "No Scaling"]
    require_page(args.proton_html, ["<SUP>1</SUP>H in In", *common])
    require_page(args.alpha_html, ["<SUP>4</SUP>He in In", *common])

    output = args.output.resolve()
    raw = output / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    raw_proton = raw / "sr_niel_v11_1_ingaas_ed15_10_10_proton.html"
    raw_alpha = raw / "sr_niel_v11_1_ingaas_ed15_10_10_alpha.html"
    shutil.copyfile(args.proton_html, raw_proton)
    shutil.copyfile(args.alpha_html, raw_alpha)

    proton = output / "sr_niel_v11_1_ingaas_ed15_10_10_proton.csv"
    alpha = output / "sr_niel_v11_1_ingaas_ed15_10_10_alpha.csv"
    proton_domain = write_charged(proton, parse_response(args.proton_html), 125)
    alpha_domain = write_charged(alpha, parse_response(args.alpha_html), 133)

    manifest = {
        "schema_version": "shieldSim.damage_response_candidate.v1",
        "preparation_status": "charged_DDD_data_prepared_not_production_enabled",
        "target": {
            "material_id": "Ga0p47In0p53As_300K",
            "description": "In0.53Ga0.47As at the material-library reference state",
            "stoichiometry": {"In": 0.53, "Ga": 0.47, "As": 1.0},
        },
        "charged_particle_definition": {
            "displacement_threshold_eV": {"In": 15.0, "Ga": 10.0, "As": 10.0},
            "model": "SR-NIEL-7 v11.1 hadronic plus Coulomb",
            "compound_rule": "SR-NIEL predefined In_xGa_(1-x)As, x=0.53; Bragg rule",
            "hadronic_threshold_scaling": "none",
            "interpolation": "log_log_between_positive_nodes",
        },
        "tables": [
            {
                "species": "proton", "path": proton.name,
                "sha256": f"sha256:{sha256(proton)}", "nodes": 125,
                "domain_min_MeV": proton_domain[0], "domain_max_MeV": proton_domain[1],
                "raw_response_sha256": f"sha256:{sha256(raw_proton)}",
            },
            {
                "species": "alpha", "path": alpha.name,
                "sha256": f"sha256:{sha256(alpha)}", "nodes": 133,
                "domain_min_MeV": alpha_domain[0], "domain_max_MeV": alpha_domain[1],
                "raw_response_sha256": f"sha256:{sha256(raw_alpha)}",
            },
        ],
        "sources": {
            "calculator": "https://www.sr-niel.asi.it/index.php/sr-niel-web-calculators/niel-calculator-for-electrons-protons-and-ions/protons-ions-niel-calculator",
            "calculator_version": "SR-NIEL-7 v11.1",
            "threshold_reference": "Beaumel et al., IEEE TNS (2020), doi:10.1109/TNS.2020.2984133",
            "threshold_reference_url": "https://hal.science/hal-03075355/document",
            "threshold_reference_sha256": "sha256:64ed276d8eec329b46087b76e9609594c3a6d863fe5d6ed21ed513ea2e92a4a4",
        },
        "unavailable": {
            "neutron_DDD": "the located publication shows a calculated curve but does not provide a downloadable response table",
            "n_eq": "no standardized InGaAs 1-MeV-neutron-equivalent denominator was found",
        },
        "limitations": [
            "candidate data are not enabled by the production loader",
            "no extrapolation beyond the positive-node domains is permitted",
            "the cited experiment found particle- and device-dependent limits to NIEL scaling",
            "no device-degradation prediction is claimed",
        ],
    }
    manifest_path = output / "candidate_manifest.v1.json"
    manifest_path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n",
                             encoding="utf-8")
    print(json.dumps({
        "manifest": str(manifest_path),
        "table_hashes": {path.name: sha256(path) for path in (proton, alpha)},
    }, indent=2, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
