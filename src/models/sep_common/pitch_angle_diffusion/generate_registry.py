#!/usr/bin/env python3
"""Generate pitch_angle_registry.inc from the specification inventory.

The model registry of the pitch-angle library is the inventory of
PITCH_ANGLE_SCATTERING_MODEL.md (specification v1.2), Section 4.2: one table
row per model ID with its defining subsection, the equations it implements
and its runtime state (Section 4.1).  The canonical companion archive that
would supply the full machine-readable registry (model_registry.json with
admissibility, capability and domain per ID) is not available (roadmap stage
PS01 is BLOCKED, see IMPLEMENTATION_STATUS.md), so the library compiles the
part of the registry that the specification itself prints, and nothing more.

What this script guarantees
  * every row of the eleven Section 4.2 tables is transcribed verbatim
    (ID, aliases, section, equation labels, runtime state);
  * the transcription is complete: the per-state counts must equal the
    Section 4.1 count table (86/6/2/31/35/12, total 172), which is an
    independent statement of the same inventory;
  * the SHA-256 of the specification file is embedded, and the C++ test
    PAD06 recomputes it, so an edited specification cannot silently disagree
    with the compiled registry.

Usage (from this directory):
  python3 generate_registry.py           # write pitch_angle_registry.inc
  python3 generate_registry.py --check   # exit 1 if the .inc is stale
"""

from __future__ import annotations

import argparse
import hashlib
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
SPEC = HERE / "PITCH_ANGLE_SCATTERING_MODEL.md"
OUTPUT = HERE / "pitch_angle_registry.inc"

# Section 4.1 count table of the specification (an independent statement of
# the inventory size per runtime state).
EXPECTED_COUNTS = {
    "READY_EXPLICIT_INPUTS": 86,
    "READY_PUBLISHED_VARIANT": 6,
    "REQUIRES_EXTERNAL_INPUT": 2,
    "REQUIRES_USER_DECISION": 31,
    "REQUIRES_SOURCE_OR_CODE_AUDIT": 35,
    "REFERENCE_DATA_ONLY": 12,
}
ROW = re.compile(
    r"^\| ([A-Z][A-Z0-9\-…\.]+)( \(alias ([^)]*)\))? \| ([0-9., ]+) \| "
    r"([^|]*) \| `([A-Z_]+)` \|$", re.M)


def c_string(text: str) -> str:
    """C++ string literal; non-ASCII (the ellipsis in PA-AMPS-I…V) as UTF-8."""
    out = []
    for byte in text.encode("utf-8"):
        if byte in (0x22, 0x5C):
            out.append("\\" + chr(byte))
        elif 0x20 <= byte < 0x7F:
            out.append(chr(byte))
        else:
            out.append("\\x%02x\"\"" % byte)
    return '"' + "".join(out) + '"'


def build() -> str:
    raw = SPEC.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    text = raw.decode("utf-8")
    start = text.index("### 4.2 Inventory by section")
    stop = text.index("## 5. Empirical")
    rows = ROW.findall(text[start:stop])
    counts = Counter(row[5] for row in rows)
    if dict(counts) != EXPECTED_COUNTS:
        raise SystemExit(f"inventory transcription incomplete: {dict(counts)} "
                         f"!= Section 4.1 {EXPECTED_COUNTS}")
    ids = [row[0] for row in rows]
    if len(set(ids)) != len(ids):
        raise SystemExit("duplicate model ID in Section 4.2")
    lines = [
        "// Generated by generate_registry.py from PITCH_ANGLE_SCATTERING_MODEL.md",
        "// Section 4.2 (specification v1.2).  Do not edit; regenerate instead.",
        f"// Rows: {len(rows)}; per-state counts equal the Section 4.1 table.",
        f'#define PITCH_ANGLE_SPECIFICATION_SHA256 "{digest}"',
        "// { id, aliases (comma separated), section, equations, runtime state }",
    ]
    for model_id, _, aliases, section, equations, state in rows:
        lines.append("    {%s, %s, %s, %s, RuntimeState::%s}," % (
            c_string(model_id), c_string(aliases.strip()),
            c_string(section.strip()), c_string(equations.strip()),
            "".join(part.capitalize() for part in state.lower().split("_"))))
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="verify that the committed .inc is current")
    args = parser.parse_args()
    generated = build()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != generated:
            print("pitch_angle_registry.inc is stale; run generate_registry.py")
            return 1
        print("pitch_angle_registry.inc matches the specification inventory")
        return 0
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
