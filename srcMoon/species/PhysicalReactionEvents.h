// These outcomes describe composition/admission, not scientific validation.
// In particular Unavailable is never a zero event rate or a transport PASS.
enum class Code { Composed, Unavailable, InvalidInput, SourceMismatch,
  OutsideDomain, NumericalFailure, ResourceLimit };
struct Status {
  Code code=Code::Composed;
  std::string message;
  bool ok()const{return code==Code::Composed;}
};
const char* CodeName(Code);

struct StateBinding {
  K::ResolvedState state;
  std::size_t catalogIndex=0;
  // A separately sourced physical mass is required for the approved reference-
  // inertia error analysis; it is NEVER replaced by the model/reference mass.
  K::MassValue physicalRestMass;
  K::ErrorLimits modelErrorLimits;
};
struct Definition {
  std::string identity,sourceProfileIdentity,sourceProfileSha256;
  std::string stateCrosswalkIdentity,stateCrosswalkSha256,energyReferenceIdentity;
  // The runtime owner must verify its reviewed source-bound mapping BEFORE
  // setting this. The composer independently checks actual state/Q/source
  // consistency as well; this flag/string is not a qualification certificate.
  bool sourceStateCrosswalkAvailable=false;
  std::vector<R::SpeciesIdentity> catalog;
  StateBinding parent,ion,electron;
  std::string channelId;
  P::SolarCase solar=static_cast<P::SolarCase>(-1); // omission is not quiet Sun
  // Exact SI conversion, supplied with its source rather than inferred from
  // an atomic fit. The numerical value must match the SI eV definition.
  Real electronVoltJ=-1;
  std::string electronVoltSourceIdentity;
  // An alternative ENERGY CONVENTION, not weaker numerical admission. The
  // normal owner must authenticate the eight-column source crosswalk before
  // supplying the physical ion formation-energy identity. No delta is input.
  K::PhotonEnergyPolicy photonEnergyPolicy=K::PhotonEnergyPolicy::SourceEqualsState;
  std::string physicalThresholdSourceIdentity;
  K::NumericControls numerical;
  K::Bound rotation; // proper-orthogonality numerical bound, dimensionless
  // Caller-owned transport admission, not generated by this module. It must
  // name the selected EXPERIMENTAL policy/evidence and actual event frame;
  // products/bath must be empty. Actual reviewed runtime admission is separate
  // from MakeEventPlan's classical software-policy flag.
  R::KinematicPolicy plannerAuthorization;
};

struct EventFrame {
  std::string inertialIdentity,eventIdentity,transformSourceIdentity;
  // v_event = R*v_inertial + offset at the SAME position/instant for all
  // material particles. The offset includes the actual state-transform
  // derivative; using only a 3x3 velocity rotation is not silently accepted.
  std::array<Real,9> inertialToEventRotation{};
  Vector3 velocityOffsetEventMS{{0,0,0}};
  bool velocityOffsetSupplied=false; // an explicitly supplied zero is valid
  double physicalEventEpochEtS=std::numeric_limits<double>::quiet_NaN();
  double geometryBasisEpochEtS=std::numeric_limits<double>::quiet_NaN();
  // Frozen environmental pose and advancing transport epochs are deliberately
  // distinct. Their caller-supplied interpretation is retained, not guessed.
  std::string epochConventionIdentity;
};
struct EventInput {
  R::ParentState parentAtEvent; // actual EVENT-coordinate position/velocity
  R::TraceInterval interval; // original unused interval; no daughter dt factor
  EventFrame frame;
  // PROPAGATION/MOMENTUM: Sun -> particle; negate a particle -> Sun ray.
  Vector3 incomingPhotonDirectionInertial{{0,0,0}};
  int pointSunVisible=-1; // exactly0/1; an event requires1
  double distanceAu=std::numeric_limits<double>::quiet_NaN();
  std::string photonGeometryIdentity;
  Real polarOpenUniform=0,azimuthOpenUniform=0;
  double ionReferenceWeight=0;
  R::OpticalDepthClock freshIonClock;
};
struct PhotonRecord {
  Real restEnergyJ=0,inertialEnergyJ=0,dopplerFactor=0;
  Vector3 inertialDirection{{0,0,0}},inertialMomentumKgMS{{0,0,0}};
  Vector3 restMomentumKgMS{{0,0,0}};
};
struct ElectronRecord {
  K::ResolvedState state;
  Vector3 inertialVelocityMS{{0,0,0}},eventVelocityMS{{0,0,0}};
  Vector3 inertialMomentumKgMS{{0,0,0}},eventMomentumKgMS{{0,0,0}};
  Real stateEnergyJ=0,inertialKineticJ=0,eventKineticJ=0;
};
struct Receipt {
  // Set by Compose from the bound target; the Na text is unchanged.
  std::string scope="EXPERIMENTAL source-mean/isotropic moving-parent Na; not validated kinetics";
  std::string modelIdentity,sourceProfileIdentity,sourceProfileSha256;
  std::string stateCrosswalkIdentity,stateCrosswalkSha256,channelId;
  std::string energyReferenceIdentity,photonGeometryIdentity;
  P::SolarCase solar=P::SolarCase::Quiet;
  P::SourceFiles sourceFiles;
  P::Channel sourceChannel;
  EventFrame frame;
  R::TraceInterval interval;
  double sourceRate1AuS=0,eventRateS=0;
  double intervalProjectedEventEpochEtS=std::numeric_limits<double>::quiet_NaN();
  Real nativeThresholdJ=0,matchedSourceMeanExcessJ=0,stateQJ=0;
  std::string photonEnergyPolicy="source-equals-state";
  Real physicalThresholdJ=0,physicalMinusSourceThresholdJ=0;
  Vector3 parentInertialVelocityMS{{0,0,0}};
  PhotonRecord incomingPhoton;
  ElectronRecord outgoingElectron;
  K::FinalState inertialProducts;
  std::array<K::ModelErrorReport,3> domainErrorReports;
  // Signed reservoir change PER PHYSICAL EVENT. These are independently
  // assembled outgoing-electron-minus-incoming-photon moments, not negatives
  // of a measured tracked residual. EventPlan scales them by represented N.
  Real bathModelMassChangeKg=0,bathInertialEnergyChangeJ=0;
  Vector3 bathInertialMomentumChangeKgMS{{0,0,0}};
  Real bathEventEnergyChangeJ=0;
  Vector3 bathEventMomentumChangeKgMS{{0,0,0}};
  double representedElectronNumberChange=0,representedPhotonNumberChange=0;
};
struct Composition {
  R::KinematicPolicy policy;
  R::EventPlan plan;
  Receipt receipt;
};

namespace detail {struct AtomicPhotoionizationData;}
// Atomic photoionization X -> X+ + e for one tracked isotope: 23Na (I21), and
// 4He, 20Ne, 40Ar (I22 atomic pilot, approved 2026-11-26; source-effective
// photon and ground ion only). The target follows from the parent state's
// nucleus; there is no caller flag and no other atom is accepted.
class AtomicPhotoionization {
 public:
  bool prepared()const{return static_cast<bool>(data_);}
  // Creates one immutable source/state/policy binding. It accepts ONLY the
  // complete single reactive D04 family of the target from the frozen registry.
  // Missing states/crosswalk/errors return Unavailable; contradictory supplied
  // claims return SourceMismatch/InvalidInput. Previous output is preserved.
  static Status Create(const P::Registry&,const Definition&,
      AtomicPhotoionization* output);
  const std::vector<R::SpeciesIdentity>* catalog()const;
  const R::Reaction* reaction()const;
  const P::Channel* sourceChannel()const;
  // D04 parent name of the bound target ("Na", "He", "Ne" or "Ar"); null if
  // the provider is not prepared.
  const char* sourceParent()const;
  // SAME production source law; no conditional branching or renormalization.
  Status RateS(double distanceAu,int pointSunVisible,double* output)const;
  // No RNG, PIC, SPICE, I/O, allocation publication or global mutation. The
  // caller supplies actual-event draws/geometry and caches this COMPLETE
  // result across allocation deferral/retry. It must not publish the receipt
  // as a committed event before the actual particle transaction commits.
  Status Compose(const EventInput&,Composition* output)const;
  // Reuse the identical admitted ion state/energy definition for the optional
  // ideal collector. This is an artificial boundary transfer, not a law for
  // lunar neutralization/retention or conversion of kinetic energy to heat.
  Status IonCollectorState(IonCollector::StateDefinition* output)const;
 private:
  std::shared_ptr<const detail::AtomicPhotoionizationData> data_;
};
// The original name of the I21 sodium binding, kept for existing callers.
