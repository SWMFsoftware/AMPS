#!/usr/bin/env python3
"""Verify campaign selection/derivation, not physical convergence.

Temporary input copies are parser fixtures, never observational evidence.
No model values or reference science baselines are generated by these tests.
"""
import csv
import json
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
import integration_common as runner


class CampaignConfiguration(unittest.TestCase):
    @staticmethod
    def write_block_fixture(path: Path, scale: float) -> None:
        """Write a rectangular raw table; values are not science evidence."""
        path.parent.mkdir(parents=True)
        with path.open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream, lineterminator="\n")
            writer.writerow(("base_block", "production_output_number",
                             "metric", "value_si"))
            for block in (1, 2):
                writer.writerow((block, block,
                                 "density_sza_0_alt_m_0",
                                 scale * (1.0 + 0.1 * block)))
                writer.writerow((block, block,
                                 "global_surface_return_rate_s",
                                 scale * (2.0 + 0.1 * block)))
                writer.writerow((block, block,
                                 "global_particle_inventory",
                                 scale * (3.0 + 0.1 * block)))

    def test_bounded_sampling_and_restart_contract(self):
        """Freeze the user-approved bounds before any linked MPI launch."""
        self.assertEqual(runner.I11_SAMPLE_LENGTH_STEPS, 500)
        self.assertEqual(runner.I11_MAXIMUM_PARTICLE_STEPS, 5000)
        self.assertEqual(runner.I11_MAXIMUM_COMPLETE_SAMPLES, 10)
        moon_build_input = (runner.REPO / "input/moon.input").read_text()
        self.assertIn("SaveParticleRestartFile=off", moon_build_input)
        self.assertNotIn("SaveParticleRestartFile=on", moon_build_input)

    def test_memory_sequence_and_fixed_physics(self):
        source = runner.REPO / "srcMoon/examples/m1_memory200.in"
        self.assertEqual(runner.qualification_levels(source), (480, 240, 120, 60))
        with tempfile.TemporaryDirectory() as directory:
            for level in runner.qualification_levels(source):
                target = Path(directory) / f"{level}.in"
                runner.derive_i11_input(source, target, level)
                self.assertEqual(float(runner.moon_setting(target,
                    "mesh_near_surface_cell_size_m")), 1000 * level)
                # Far-domain resolution and physical extent must not vary:
                # these gates isolate near-surface discretization error.
                for key in ("mesh_far_field_cell_size_m", "mesh_outer_cell_size_m",
                            "mesh_near_surface_extent_m", "mesh_far_field_extent_m",
                            "simulation_start_utc", "random_seed"):
                    self.assertEqual(runner.moon_setting(source, key),
                                     runner.moon_setting(target, key))
            # I13 must reproduce exactly the finest I11 input, not merely
            # equivalent floating-point values with a different input hash.
            baseline = Path(directory) / "baseline.in"
            runner.derive_i11_input(source, baseline, 60)
            self.assertEqual(runner.sha256(baseline),
                             runner.sha256(Path(directory) / "60.in"))

    def test_legacy_full_preserved(self):
        source = runner.REPO / "srcMoon/examples/m1_sphere.in"
        self.assertEqual(runner.qualification_levels(source), (40, 20, 10, 5))
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "5.in"
            runner.derive_i11_input(source, target, 5)
            self.assertEqual(runner.moon_setting(target,
                             "mesh_near_surface_cell_size_m"), "5000")

    def test_unapproved_custom_is_rejected(self):
        source = runner.REPO / "srcMoon/examples/m1_memory200.in"
        with tempfile.TemporaryDirectory() as directory:
            target = Path(directory) / "changed.in"
            target.write_text(source.read_text().replace(
                "mesh_far_field_cell_size_m = 480000",
                "mesh_far_field_cell_size_m = 120000"))
            with self.assertRaises(runner.MissingPrerequisite):
                runner.qualification_levels(target)
            with self.assertRaises(ValueError):
                runner.derive_i11_input(target, Path(directory) / "invalid.in", 480)
        with self.assertRaises(runner.MissingPrerequisite):
            runner.qualification_levels(runner.REPO / "srcMoon/examples/m1_quick.in")

    def test_stage_diagnostics_are_cumulative_and_unqualified(self):
        """Every finished resolution gets plots that cannot become a gate."""
        with tempfile.TemporaryDirectory() as directory:
            campaign = Path(directory)
            self.write_block_fixture(campaign / "480km/block_metrics.csv", 1.0)
            first = runner.render_i11_stage_diagnostic(
                campaign, [480], runner.FAIL)
            self.assertFalse(first["accepted_convergence_input"])
            self.assertFalse(first["observational_validation"])
            for suffix in ("csv", "png", "eps", "json"):
                self.assertTrue((campaign / f"480km/stage_diagnostic.{suffix}").is_file())

            self.write_block_fixture(campaign / "240km/block_metrics.csv", 1.25)
            second = runner.render_i11_stage_diagnostic(
                campaign, [480, 240], runner.PASS)
            self.assertEqual(second["completed_resolutions_km"], [480, 240])
            metadata = json.loads(
                (campaign / "240km/stage_diagnostic.json").read_text())
            self.assertEqual(metadata["formal_level_status"], runner.PASS)
            with (campaign / "240km/stage_diagnostic.csv").open(
                    newline="", encoding="utf-8") as stream:
                rows = list(csv.DictReader(stream))
            self.assertEqual({row["resolution_km"] for row in rows},
                             {"480", "240"})
            self.assertTrue(all(row["evidence_class"] ==
                                "unqualified-raw-diagnostic" for row in rows))
            current = [row for row in rows if row["resolution_km"] == "240"]
            self.assertTrue(all(row["relative_change_from_previous"]
                                for row in current))


if __name__ == "__main__":
    unittest.main()
