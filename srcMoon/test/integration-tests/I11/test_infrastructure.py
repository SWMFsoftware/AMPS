class CampaignConfiguration(unittest.TestCase):
    def test_normal_builder_explicitly_leaves_nightly_mode(self):
        """Verify configuration intent with protocol files, never an AMPS run.

        Application selection alone does not clear Config.pl's persisted
        TESTMODE. Capture the actual shared builder commands and require OFF;
        the real clean normal-mode campaign separately verifies its effects.
        """
        import run_integration_tests as builds
        commands = []
        with tempfile.TemporaryDirectory(prefix="amps-build-mode-protocol-") as directory:
            root = Path(directory)
            (root / "amps").write_text("protocol placeholder, not an executable\n")
            def command(arguments, log):
                commands.append(arguments)
                return 0
            with patch.object(builds, "REPO", root), \
                    patch.object(builds, "command_log", side_effect=command):
                builds.clean_configure_build("moon", "/protocol/spice",
                    "/protocol/kernels", root / "evidence", "normal")
            self.assertIn("-amps-test=off", commands[0])
            self.assertNotIn("-amps-test=on", commands[0])

    def test_regression_i12_launches_without_qualification_reuse(self):
        """Protect the launcher/artifact protocol, never a physical result.

        The isolated launcher writes only a protocol ID and explicit fixture
        logs. Mocked scoring cannot provide scientific PASS. The separate real
        eight-rank registered MOON-I12 rerun verifies the production path.
        An accidental qualification-grid query before launch fails this test,
        because CUSTOM regression inputs cannot have qualified I11 companions.
        """
        source = runner.REPO / "srcMoon/examples/m1_regression.in"
        def launch(command, runtime, environment, stdout, stderr, resources):
            receipt = Path(command[command.index("--integration-output") + 1])
            receipt.write_text("test_id=I12\n")
            stdout.write_text("protocol fixture; model not executed\n")
            stderr.write_text("")
            return 0
        with tempfile.TemporaryDirectory(prefix="amps-i12-protocol-") as directory:
            output = Path(directory)
            with patch.object(runner, "manifest", return_value={"inputs": {}}), \
                    patch.object(runner, "qualification_levels", side_effect=AssertionError(
                        "regression launch queried qualification-only receipt reuse")), \
                    patch.object(runner, "run_monitored", side_effect=launch) as execute, \
                    patch.object(runner, "check", return_value=(
                        runner.SKIPPED, {}, "protocol fixture; unqualified input")):
                code = runner.run("I12", Path("/protocol-only-not-an-AMPS-binary"),
                                  output, source, 8, "regression")
            self.assertEqual(code, 77)
            execute.assert_called_once()
            result = json.loads((output / "I12/result.json").read_text())
            self.assertEqual(result["status"], runner.SKIPPED)
            for name in ("stdout.log", "stderr.log", "receipt.txt",
                         "run_manifest.json", "application.in"):
                self.assertTrue((output / "I12" / name).is_file(), name)

    def test_species_builder_preserves_preexisting_temporary_input(self):
        """Refusing a filename collision must not delete the conflicting file."""
        path = runner.TEST_ROOT / "build_m2_qualification.py"
        specification = importlib.util.spec_from_file_location("species_builder", path)
        module = importlib.util.module_from_spec(specification)
        specification.loader.exec_module(module)
        with tempfile.TemporaryDirectory() as directory:
            root = Path(directory)
            (root / "input").mkdir()
            (root / "input/moon.input").write_text("configuration preflight fixture\n")
            output = root / "result"
            token = module.hashlib.sha256(str(output.resolve()).encode()).hexdigest()[:12]
            existing = root / f"input/moon_m2_qualification_{token}.input"
            marker = b"pre-existing input must survive a refused build\n"
            existing.write_bytes(marker)
            with patch.object(module, "REPO", root), patch.object(sys, "argv", [
                    str(path), "--purpose", "sampling", "--output-dir", str(output),
                    "--spice-path", str(root / "spice"),
                    "--spice-kernels", str(root / "kernels")]):
                self.assertEqual(module.main(), 2)
            self.assertEqual(existing.read_bytes(), marker)
            receipt = json.loads((output / "build-m2-na-ar.json").read_text())
            self.assertEqual(receipt["status"], "ERROR")
            self.assertIn("refusing to overwrite", receipt["error"])
            self.assertEqual(receipt["commands"], [])

    def make_jobs(self, output, programs):
        """Create scheduler fixtures only; these processes produce no science."""
        jobs = {}
        for key, program in enumerate(programs):
            directory = output / str(key)
            (directory / "runtime").mkdir(parents=True)
            jobs[key] = {"directory": directory,
                         "command": [sys.executable, "-c", program]}
        return jobs

    def test_parallel_scheduler_preserves_all_exit_codes(self):
        """A failed child must not prevent the remaining result from being reaped."""
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            jobs = self.make_jobs(output, ["raise SystemExit(5)", "pass"])
            with patch.object(runner, "render_i11_stage_diagnostic") as render:
                codes = execute_levels(jobs, output, 2, 10)
            self.assertEqual(codes, {0: 5, 1: 0})
            self.assertEqual(render.call_count, 1)
            self.assertEqual(render.call_args.args[-1], "PENDING")
            self.assertTrue((output / "campaign_resources.csv").is_file())

    def test_parallel_deadline_reaps_children(self):
        """A runtime budget yields ERROR evidence, never a completed science gate."""
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            jobs = self.make_jobs(output, ["import time; time.sleep(20)"])
            codes = execute_levels(jobs, output, 1, 0.05)
            self.assertEqual(codes, {0: 124})
            evidence = json.loads((output / "execution_termination.json").read_text())
            self.assertEqual(evidence["status"], "ERROR")
            self.assertIn("runtime budget", evidence["reason"])

    def test_parallel_aggregate_memory_guard(self):
        """Exercise the operational guard with a deliberately tiny fixture budget."""
        with tempfile.TemporaryDirectory() as directory:
            output = Path(directory)
            jobs = self.make_jobs(output, ["import time; time.sleep(20)"])
            codes = execute_levels(jobs, output, 1, 10, memory_gib=1e-12)
            self.assertEqual(codes, {0: 124})
            evidence = json.loads((output / "execution_termination.json").read_text())
            self.assertIn("aggregate process-tree RSS", evidence["reason"])

    @staticmethod
    def write_block_fixture(path: Path, scale: float) -> None:
        """Write a rectangular raw table; values are not science evidence."""
        path.parent.mkdir(parents=True)
        (path.parent / "analysis_diagnostics.csv").write_text(
            "base_blocks,batch_size_base_blocks,batch_count,lag1_significance,"
            "independence_failed_metrics,equilibrium_failed_checks,ci_failed_metrics,first_failed_gate\n")
        with path.open("w", newline="", encoding="utf-8") as stream:
            writer = csv.writer(stream, lineterminator="\n")
            writer.writerow(("base_block", "production_output_number",
                             "metric", "value_si"))
            for block in (1, 2):
                writer.writerow((block, block,
                                 "density_sza_0_alt_m_0",
                                 scale * (1.0 + 0.1 * block)))
                writer.writerow((block, block,
                                 "global_surface_return_rate_s",
                                 scale * (2.0 + 0.1 * block)))
                writer.writerow((block, block,
                                 "global_particle_inventory",
                                 scale * (3.0 + 0.1 * block)))

