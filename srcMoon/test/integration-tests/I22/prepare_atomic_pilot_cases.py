def deck(element, order, endpoint):
    lines = [line for line in BASE_DECK.read_text().splitlines(keepends=True) if not line.startswith('!')]
    cap = revised()[1].get(f'{element}-{endpoint}')
    out = []
    for line in lines:
        key = line.split('=', 1)[0].strip()
        if key == 'tracing_maximum_substep_s' and cap is not None:
            if line.split('=', 1)[1].strip() != cap['from']:
                raise ValueError('revision b does not start from the base deck substep cap')
            line = f'tracing_maximum_substep_s = {cap["to"]}\n'
        elif key == 'particle_tracing_mover':
            line = f'particle_tracing_mover = force-cut-surface-{order}-order\n'
        elif key == 'photochemistry_solar_case':
            line = f'photochemistry_solar_case = {endpoint}\n'
        elif line.strip() == '#end application':
            gas = GAS[element]
            out += [f'{gas}_to_sodium_reference_weight_ratio = 1\n',
                    f'{gas}_ion_characteristic_speed_m_s = 1e3\n',
                    f'{gas}_ion_to_sodium_reference_weight_ratio = 1\n']
        out.append(line)
    for required in ('particle_tracing_mover', 'photochemistry_solar_case', 'tracing_maximum_substep_s'):
        if sum(1 for l in out if l.split('=', 1)[0].strip() == required) != 1:
            raise ValueError('base deck must contain exactly one ' + required)
    if sum(1 for l in out if l.strip() == '#end application') != 1:
        raise ValueError('base deck must contain exactly one application end')
    return HEADER + ''.join(out)


def revised():
    """(parent counts, substep caps) after applying the approved revisions in order.

    Only two fields may be revised: original_parents (case controls) and
    tracing_maximum_substep_s (application deck). Each change must start from
    the current value; expected_events_at_1AU_rates is documentation only.
    """
    counts = dict(json.loads(APPROVAL.read_text())['cases']['original_parents'])
    caps = {}
    for path in REVISIONS:
        revision = json.loads(path.read_text())
        if revision.get('status') != 'APPROVED':
            raise ValueError('revision is not approved: ' + path.name)
        for name, change in revision['changes'].items():
            if name not in counts:
                raise ValueError('revision names an unknown case: ' + name)
            for field, value in change.items():
                if field == 'original_parents':
                    if counts[name] != value['from']:
                        raise ValueError('revision does not start from the approved count: ' + name)
                    counts[name] = value['to']
                elif field == 'tracing_maximum_substep_s':
                    if name in caps:
                        raise ValueError('substep cap revised twice: ' + name)
                    caps[name] = value
                elif field != 'expected_events_at_1AU_rates':
                    raise ValueError('revision changes an unrevisable field: ' + field)
    return counts, caps


def parent_counts():
    """Approved parent counts with the later approved revisions applied."""
    return revised()[0]


def cases():
    approval = json.loads(APPROVAL.read_text())['cases']
    parents = parent_counts()
    out = {}
    for element in GAS:
        for endpoint in ('quiet', 'active'):
            name = f'{element}-{endpoint}'
            horizon = int(approval['horizons_s'][name])
            if horizon % 32:
                raise ValueError('horizon must divide exactly into 8, 16 and 32 steps')
            value = copy.deepcopy(json.loads(BASE_CONTROLS.read_text()))
            value['cohort_id'] = f'atomic-I22-pilot-{name}-seed731993'
            value['controls'].update(
                case_kind='trajectory-integrated-hazard', earth_occultation='off', solar_endpoint=endpoint,
                reference_weight_mode='explicit', parent_reference_weight='7', ion_reference_weight='7',
                optical_clock_precision='compensated-extended-log',
                parent_compiled_species='1', ion_compiled_species='2',
                maximum_classical_speed_ms='3.4e6', model_identity=POLICY_IDENTITY,
                transport_policy_evidence_file='../atomic_pilot_protocol.json',
                transport_policy_evidence_sha256=hashlib.sha256(protocol_text().encode()).hexdigest(),
                transport_policy_identity=POLICY_IDENTITY,
                original_parents=str(parents[name]),
                physical_horizon_s=str(horizon), physical_step_s=str(horizon // 8), physical_steps='8',
                source_position_lso_m_0='10000000', source_position_lso_m_1='0', source_position_lso_m_2='0',
                source_velocity_lso_ms_0='1', source_velocity_lso_ms_1='0', source_velocity_lso_ms_2='0')
            out[name] = value
    return out


def render():
    files = {}
    for element in GAS:
        for order in ('first', 'second'):
            for endpoint in ('quiet', 'active'):
                files[f'{element}_{order}_{endpoint}.in'] = deck(element, order, endpoint)
    for name, value in cases().items():
        files[f'{name}.json'] = json.dumps(value, indent=2) + '\n'
        # Revision b rule: the mover substep cap equals the coarsest common step,
        # so refining the common step also refines the photon-history segments.
        element, endpoint = name.split('-')
        for order in ('first', 'second'):
            cap = [l.split('=', 1)[1].strip() for l in files[f'{element}_{order}_{endpoint}.in'].splitlines()
                   if l.split('=', 1)[0].strip() == 'tracing_maximum_substep_s']
            if cap != [value['controls']['physical_step_s']]:
                raise ValueError('substep cap must equal the coarsest common step: ' + name)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    if args.check:
        bad = [n for n, text in files.items() if not (FROZEN / n).is_file() or (FROZEN / n).read_text() != text]
        if not PROTOCOL.is_file() or PROTOCOL.read_text() != protocol_text():
            bad.append(PROTOCOL.name)
        if bad or sorted(p.name for p in FROZEN.iterdir()) != sorted(files):
            print('differs from frozen reference/atomic_pilot: ' + ', '.join(bad), file=sys.stderr)
            return 1
        print('reference/atomic_pilot reproduced byte for byte')
        return 0
    FROZEN.mkdir(exist_ok=True)
    PROTOCOL.write_text(protocol_text())
    for name, text in files.items():
        (FROZEN / name).write_text(text)
    print(json.dumps(sorted(files), indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
