from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
I21 = HERE.parent / 'I21/reference'
BASE_DECK = I21 / 'shadow_sphere.in'
BASE_CONTROLS = I21 / 'shadow_controls.json'
APPROVAL = HERE / 'reference/atomic_pilot_approval_20261126.json'
REVISION = HERE / 'reference/atomic_pilot_revision_20261126.json'
REVISION_B = HERE / 'reference/atomic_pilot_revision_20261126b.json'
REVISIONS = (REVISION, REVISION_B)
PROTOCOL = HERE / 'reference/atomic_pilot_protocol.json'
FROZEN = HERE / 'reference/atomic_pilot'
GAS = {'He': 'helium', 'Ne': 'neon', 'Ar': 'argon'}
POLICY_IDENTITY = 'approved-I22-atomic-pilot-source-effective-photon-ground-ion-v1'
HEADER = ('! I22 atomic-pilot case deck (approved 2026-11-26), generated by\n'
          '! integration-tests/I22/prepare_atomic_pilot_cases.py from ../I21/reference/shadow_sphere.in.\n'
          '! Compact verification mesh only; no convergence or observational claim.\n'
          '! The parent/ion startup keys only admit normal startup; the cohort owner\n'
          '! resets the time steps to the common step and assigns the reference weights.\n')


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


