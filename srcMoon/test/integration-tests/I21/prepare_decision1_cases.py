#!/usr/bin/env python3
"""Generate the I21 decision-1 case controls and application decks (approved 2026-11-26).

Derived deterministically from the committed compact sphere deck
(reference/shadow_sphere.in) and its controls (reference/shadow_controls.json);
only the explicitly approved fields change. See DECISION1_CONTRACT.md.

Cases (Na, D04, frozen LSO, sphere Moon, seed 731993, 8/16/32 steps x 1/8 ranks):
  weights-1to8, weights-8to1   x0 = 1e7 m, v = +256 m/s along x, SPICE Sun,
                               Na:Na+ reference weights 7:56 and 56:7
  sun-1au-quiet ... -active    the same line, prescribed static Sun exactly
  sun-2au-quiet ... -active    1 AU or 2 AU from the start along +x
  moon-shadow                  start (-4e6, -4e6, 0) m, v = 122.0703125 m/s along +y
  lunar-gravity                start (0, 1e7, 0) m, v = 600 m/s along +z,
                               16,384 s horizon, 1,024 parents, gravity-only build
Each case runs with both movers; the decks differ only in the mover line, the
active decks select the active D04 endpoint (the normal runtime refuses a
deck whose endpoint differs from the cohort), and the gravity decks select
fixed-step tracing with a maximum substep of 16,384 s, so each outer step is
one substep.

Use --check to require byte equality with reference/decision1/.
"""
import argparse
import copy
import json
from pathlib import Path
import sys

HERE = Path(__file__).resolve().parent
BASE_DECK = HERE / 'reference/shadow_sphere.in'
BASE_CONTROLS = HERE / 'reference/shadow_controls.json'
FROZEN = HERE / 'reference/decision1'
AU = 149597870700                      # IAU 2012 Resolution B2 [m], exact integer
X0 = 10000000                          # straight-line start [m]

HEADER = ('! I21 decision-1 case deck (approved 2026-11-26), generated by\n'
          '! integration-tests/I21/prepare_decision1_cases.py from reference/shadow_sphere.in.\n'
          '! Compact verification mesh only; no convergence or observational claim.\n')


def deck(order, gravity, endpoint='quiet'):
    lines = BASE_DECK.read_text().splitlines(keepends=True)
    body = [line for line in lines if not line.startswith('!')]
    out = []
    for line in body:
        key = line.split('=', 1)[0].strip()
        if key == 'particle_tracing_mover':
            line = f'particle_tracing_mover = force-cut-surface-{order}-order\n'
        elif gravity and key == 'tracing_adaptive':
            line = 'tracing_adaptive = false\n'
        elif gravity and key == 'tracing_maximum_substep_s':
            line = 'tracing_maximum_substep_s = 16384\n'
        elif key == 'photochemistry_solar_case':
            line = f'photochemistry_solar_case = {endpoint}\n'
        out.append(line)
    text = HEADER + ''.join(out)
    for required in ('particle_tracing_mover', 'tracing_adaptive', 'tracing_maximum_substep_s',
                     'photochemistry_solar_case'):
        if sum(1 for l in out if l.split('=', 1)[0].strip() == required) != 1:
            raise ValueError('base deck must contain exactly one ' + required)
    return text


def controls(name, **changes):
    base = json.loads(BASE_CONTROLS.read_text())
    value = copy.deepcopy(base)
    value['cohort_id'] = f'sodium-I21-d1-{name}-seed731993'
    c = value['controls']
    c.update(case_kind='trajectory-integrated-hazard', earth_occultation='off', solar_endpoint='quiet',
             reference_weight_mode='explicit', parent_reference_weight='7', ion_reference_weight='7',
             optical_clock_precision='compensated-extended-log',
             transport_policy_evidence_file='../../../../M3_P02_CONTROLLED_NA_PROTOCOL.json',
             source_position_lso_m_0=str(X0), source_position_lso_m_1='0', source_position_lso_m_2='0',
             source_velocity_lso_ms_0='256', source_velocity_lso_ms_1='0', source_velocity_lso_ms_2='0')
    c.update(changes)
    return value


def cases():
    out = {
        'weights-1to8': controls('weights-1to8', parent_reference_weight='7', ion_reference_weight='56'),
        'weights-8to1': controls('weights-8to1', parent_reference_weight='56', ion_reference_weight='7'),
        'moon-shadow': controls('moon-shadow', source_position_lso_m_0='-4000000', source_position_lso_m_1='-4000000',
                                source_velocity_lso_ms_0='0', source_velocity_lso_ms_1='122.0703125'),
        'lunar-gravity': controls('lunar-gravity', case_kind='trajectory-lunar-gravity', original_parents='1024',
                                  physical_horizon_s='16384', physical_step_s='2048', physical_steps='8',
                                  source_position_lso_m_0='0', source_position_lso_m_1='10000000',
                                  source_velocity_lso_ms_0='0', source_velocity_lso_ms_2='600'),
    }
    for distance in (1, 2):
        for endpoint in ('quiet', 'active'):
            name = f'sun-{distance}au-{endpoint}'
            out[name] = controls(name, solar_endpoint=endpoint, photon_source_geometry='prescribed-static-point-sun',
                                 prescribed_sun_identity=f'I21-decision1-static-point-Sun-{distance}AU-on-+x-from-start',
                                 prescribed_sun_position_lso_m_0=str(X0 + distance * AU),
                                 prescribed_sun_position_lso_m_1='0', prescribed_sun_position_lso_m_2='0')
    return out


def render():
    files = {}
    for order in ('first', 'second'):
        files[f'straight_{order}.in'] = deck(order, False)
        files[f'straight_{order}_active.in'] = deck(order, False, 'active')
        files[f'gravity_{order}.in'] = deck(order, True)
    for name, value in cases().items():
        files[f'{name}.json'] = json.dumps(value, indent=2) + '\n'
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--output-dir', type=Path, default=FROZEN)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files = render()
    if args.check:
        bad = [n for n, text in files.items() if (FROZEN / n).read_text() != text]
        if bad or sorted(p.name for p in FROZEN.iterdir()) != sorted(files):
            print('differs from frozen reference/decision1: ' + ', '.join(bad), file=sys.stderr)
            return 1
        print('reference/decision1 reproduced byte for byte')
        return 0
    args.output_dir.mkdir(parents=True, exist_ok=args.output_dir == FROZEN)
    for name, text in files.items():
        (args.output_dir / name).write_text(text)
    print(json.dumps(sorted(files), indent=2))
    return 0


if __name__ == '__main__':
    sys.exit(main())
