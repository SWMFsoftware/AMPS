"""Protocol-only retained-build/configuration controls; no model physics run.

Temporary byte strings below represent ABI receipts/headers/executables only.
They are never executed, interpreted as physical output or published as native
build evidence. The tests mutate actual files consumed by the production
identity verifier and check isolation between live-probe and retained modes.
"""
