sys.path.insert(0, str(TEST_ROOT))
import build_m2_qualification as builder


class RetainedBuildIdentity(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="m2-build-protocol-only-")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.repo = self.root/"source"
        self.bundle = self.root/"bundle"
        self.bundle.mkdir()
        self.patch = patch.object(builder, "REPO", self.repo)
        self.patch.start(); self.addCleanup(self.patch.stop)
        self.source = self.write(self.repo/"srcMoon/native.cpp",
            "// Protocol identity only; never compiled.\n")
        self.write(self.repo/"Config.pl", "# Protocol-only configuration identity\n")
        self.generated = {}
        for relative in ("pic/picGlobal.dfn", "general/rnd.h", "pic/pic.h", "models/exosphere/Exosphere.dfn"):
            text = "PROTOCOL-ONLY GENERATED BYTES: "+relative+"\n"
            live = self.write(self.repo/"build"/relative, text)
            retained = self.write(self.bundle/"generated-configuration"/relative, text)
            self.generated[relative] = {"path": str(retained.relative_to(self.bundle)),
                                        "sha256": builder.sha256(retained)}
        self.executable = self.write(self.bundle/"amps-moon-m2-na-ar",
            "PROTOCOL-ONLY EXECUTABLE BYTES; NEVER EXECUTED\n")
        self.receipt = self.bundle/"build-m2-na-ar.json"
        self.document = {"schema": "srcMoon-M2-Na-Ar-build-v1", "purpose": "m2", "status": "PASS",
            "executable": {"path": str(self.executable), "sha256": builder.sha256(self.executable)},
            "production_source_hashes": builder.production_source_identity(),
            "i19_chemistry_contract": {"photolytic_reactions": "OFF",
                "generated_definitions_sha256": self.generated["pic/picGlobal.dfn"]["sha256"]},
            "rng_contract": {"mode": "MERSENNE_TWISTER",
                "generated_header_sha256": self.generated["general/rnd.h"]["sha256"]},
            "retained_generated_files": copy.deepcopy(self.generated)}
        # These temporary bytes test receipt authentication only. They are
        # not a real preprocessor result, executable, or scientific approval.
        self.document["effective_configuration"]={
            "schema":"srcMoon-M2-effective-configuration-v1","status":"PASS",
            "photolytic_reactions":"OFF","individual_particle_weights":"ON",
            "rng":"MERSENNE_TWISTER","executable_sha256":builder.sha256(self.executable)}
        for name in ("probe_source","macro_dump"):
            path=self.write(self.bundle/(name+".txt"),"PROTOCOL-ONLY proof bytes: "+name+"\n")
            self.document["effective_configuration"][name]={"path":path.name,"sha256":builder.sha256(path)}
        self.save()

    def write(self, path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        return path

    def save(self):
        self.receipt.write_text(json.dumps(self.document, indent=2)+"\n")

    def verify(self, *, strict=True):
        return builder.verify_retained_executable(self.executable,
            require_current_generated_tree=strict)

    def test_strict_default_accepts_matching_live_and_retained_bytes(self):
        self.assertEqual(builder.verify_retained_executable(self.executable)["status"], "PASS")

    def test_retained_mode_accepts_after_unrelated_live_reconfiguration(self):
        for relative in self.generated:
            live = self.repo/"build"/relative
            original = live.read_bytes()
            live.write_text("UNRELATED LATER PROFILE: "+relative+"\n")
            with self.subTest(relative=relative):
                self.assertEqual(self.verify(strict=False)["status"], "PASS")
                with self.assertRaises(ValueError): self.verify()
                with self.assertRaises(ValueError): builder.verify_retained_executable(self.executable)
            live.write_bytes(original)

    def test_retained_mode_accepts_when_live_generated_tree_is_absent(self):
        shutil.rmtree(self.repo/"build")
        self.assertEqual(self.verify(strict=False)["status"], "PASS")
        with self.assertRaises(ValueError): self.verify()

    def test_each_preserved_header_tamper_is_rejected_in_both_modes(self):
        for relative in self.generated:
            retained = self.bundle/self.generated[relative]["path"]
            original = retained.read_bytes()
            retained.write_bytes(original+b"ALTERED\n")
            for strict in (False, True):
                with self.subTest(relative=relative, strict=strict), self.assertRaises(ValueError):
                    self.verify(strict=strict)
            retained.write_bytes(original)

    def test_missing_snapshot_never_falls_back_to_matching_live_tree(self):
        for relative in self.generated:
            record = self.document["retained_generated_files"].pop(relative)
            self.save()
            with self.subTest(relative=relative), self.assertRaises(ValueError):
                self.verify(strict=False)
            self.document["retained_generated_files"][relative] = record
        self.document.pop("retained_generated_files")
        self.save()
        with self.assertRaises(ValueError): self.verify(strict=False)

    def test_missing_preserved_file_is_not_replaced_by_live_copy(self):
        path = self.bundle/self.generated["pic/picGlobal.dfn"]["path"]
        path.unlink()
        for strict in (False, True):
            with self.subTest(strict=strict), self.assertRaises(ValueError): self.verify(strict=strict)

    def test_successful_receipt_and_executable_hash_are_required(self):
        self.document["status"] = "ERROR"; self.save()
        with self.assertRaises(ValueError): self.verify(strict=False)
        self.document["status"] = "PASS"; self.save()
        self.executable.write_bytes(b"WRONG PROTOCOL EXECUTABLE")
        with self.assertRaises(ValueError): self.verify(strict=False)

    def test_changed_authoritative_source_rejects_retained_and_strict_modes(self):
        self.source.write_text("// Changed native model identity.\n")
        for strict in (False, True):
            with self.subTest(strict=strict), self.assertRaises(ValueError): self.verify(strict=strict)

    def test_changed_configuration_preprocessor_library_invalidates_build(self):
        # Protocol-only Perl bytes, never a generated build or physical input.
        # The launcher may remain identical while its delegated macro-guard
        # logic changes; that dependency must invalidate both verification
        # modes, even with unchanged retained executable/header snapshots.
        library=self.write(self.repo/"ampsConfigLib.pm","# CONTROL preprocessor version one\n")
        self.document["production_source_hashes"]=builder.production_source_identity()
        self.assertIn("ampsConfigLib.pm",self.document["production_source_hashes"])
        self.save()
        library.write_text("# CONTROL changed macro-guard preprocessing\n")
        for strict in (False,True):
            with self.subTest(strict=strict),self.assertRaises(ValueError):
                self.verify(strict=strict)

    def test_changed_builder_recipe_invalidates_retained_and_strict_modes(self):
        recipe=self.write(self.repo/"srcMoon/test/build_m2_qualification.py","# Protocol recipe one\n")
        self.document["production_source_hashes"]=builder.production_source_identity()
        self.assertIn("srcMoon/test/build_m2_qualification.py",self.document["production_source_hashes"])
        self.save(); recipe.write_text("# Protocol changed effective-mode recipe\n")
        for strict in (False,True):
            with self.subTest(strict=strict),self.assertRaises(ValueError):self.verify(strict=strict)

    def test_missing_effective_proof_rejects_early_off_only_legacy_receipt(self):
        self.document.pop("effective_configuration");self.save()
        for strict in (False,True):
            with self.subTest(strict=strict),self.assertRaisesRegex(ValueError,"effective compiled"):
                self.verify(strict=strict)

    def test_effective_proof_bytes_and_executable_binding_are_required(self):
        original=copy.deepcopy(self.document["effective_configuration"])
        for name in ("probe_source","macro_dump"):
            record=original[name];path=self.bundle/record["path"];data=path.read_bytes()
            path.write_bytes(data+b"changed proof\n")
            for strict in (False,True):
                with self.subTest(name=name,strict=strict),self.assertRaises(ValueError):self.verify(strict=strict)
            path.write_bytes(data)
        for key,value in (("photolytic_reactions","ON"),("individual_particle_weights","OFF"),
                          ("rng","OTHER"),("executable_sha256","0"*64)):
            self.document["effective_configuration"]=copy.deepcopy(original)
            self.document["effective_configuration"][key]=value;self.save()
            for strict in (False,True):
                with self.subTest(key=key,strict=strict),self.assertRaises(ValueError):self.verify(strict=strict)

    def test_changed_shared_species_input_invalidates_retained_physics(self):
        # This is identity-only protocol text, never a physical species table.
        # Physical masses/charges live outside .cpp/.h and must still bind the
        # executable; a prior header snapshot cannot excuse different inputs.
        table=self.write(self.repo/"input/species.input","PROTOCOL species version one\n")
        self.document["production_source_hashes"]=builder.production_source_identity()
        self.assertIn("input/species.input",self.document["production_source_hashes"])
        self.save();self.assertEqual(self.verify(strict=False)["status"],"PASS")
        table.write_text("PROTOCOL species version two\n")
        for strict in (False,True):
            with self.subTest(strict=strict), self.assertRaises(ValueError): self.verify(strict=strict)

    def test_new_untracked_native_source_invalidates_build_identity(self):
        self.write(self.repo/"srcMoon/new_kernel.h", "// New production input.\n")
        with self.assertRaises(ValueError): self.verify(strict=False)

    def test_removed_native_source_invalidates_build_identity(self):
        self.source.unlink()
        with self.assertRaises(ValueError): self.verify(strict=False)

    def test_receipt_contract_hashes_must_match_snapshot_hashes(self):
        self.document["i19_chemistry_contract"]["generated_definitions_sha256"] = "0"*64
        self.save()
        with self.assertRaises(ValueError): self.verify(strict=False)
        self.document["i19_chemistry_contract"]["generated_definitions_sha256"] = self.generated["pic/picGlobal.dfn"]["sha256"]
        self.document["rng_contract"]["generated_header_sha256"] = "0"*64
        self.save()
        with self.assertRaises(ValueError): self.verify(strict=False)

    def test_relative_snapshot_bundle_survives_copy_and_original_removal(self):
        copied = self.root/"copied-bundle"
        shutil.copytree(self.bundle, copied)
        shutil.rmtree(self.bundle)
        value = builder.verify_retained_executable(copied/self.executable.name,
            require_current_generated_tree=False)
        self.assertEqual(value["status"], "PASS")

    def test_legacy_live_only_receipt_is_rejected_in_both_modes(self):
        self.document.pop("retained_generated_files"); self.save()
        for strict in (False,True):
            with self.subTest(strict=strict),self.assertRaises(ValueError):self.verify(strict=strict)

    def test_malformed_receipt_and_snapshot_shapes_are_controlled_errors(self):
        # JSON may parse successfully while the schema is corrupt. Rejection
        # must be ValueError (the runner's controlled ERROR path), rather than
        # an uncaught AttributeError/TypeError or a successful identity check.
        original = copy.deepcopy(self.document)
        documents = [None, [], "not-a-receipt"]
        for field, values in (
                ("executable", (None, [], "bad")),
                ("i19_chemistry_contract", ([], "bad")),
                ("rng_contract", (None, [], "bad")),
                ("retained_generated_files", (None, [], "bad"))):
            for value in values:
                changed = copy.deepcopy(original); changed[field] = value
                documents.append(changed)
        for record in (None, [], "bad", {}, {"path": None}, {"path": []}):
            changed = copy.deepcopy(original)
            changed["retained_generated_files"]["pic/pic.h"] = record
            documents.append(changed)
        for index, document in enumerate(documents):
            self.document = document; self.save()
            with self.subTest(index=index), self.assertRaises(ValueError):
                self.verify(strict=False)


class EffectiveCompilerConfiguration(unittest.TestCase):
    """Real preprocessor on labelled minimal headers, not a lunar model."""
    def headers(self,root,late):
        build=root/"build";(build/"pic").mkdir(parents=True);(build/"main").mkdir()
        (build/"pic/pic.h").write_text("""// PROTOCOL ONLY: no physical kernel.
#define _PIC_PHOTOLYTIC_REACTIONS_MODE_OFF_ 1
#define _PIC_PHOTOLYTIC_REACTIONS_MODE_ON_ 0
#define _PIC_PHOTOLYTIC_REACTIONS_MODE_ _PIC_PHOTOLYTIC_REACTIONS_MODE_OFF_
#define _INDIVIDUAL_PARTICLE_WEIGHT_ON_ 1
#define _INDIVIDUAL_PARTICLE_WEIGHT_MODE_ _INDIVIDUAL_PARTICLE_WEIGHT_ON_
#define _RND_MODE_MERSENNE_TWISTER_ 2
#define _RND_MODE_ _RND_MODE_MERSENNE_TWISTER_
""")
        (build/"main/Moon.h").write_text("// PROTOCOL ONLY: application include ordering.\n"+late)
        return build

    def test_real_preprocessor_accepts_matching_modes(self):
        compiler=shutil.which("g++")
        if not compiler:self.skipTest("C++ preprocessor unavailable")
        with tempfile.TemporaryDirectory(prefix="m2-effective-control-") as tmp:
            root=Path(tmp);build=self.headers(root,"")
            with patch.object(builder,"REPO",root):
                result=builder.effective_configuration(build,root,root/"proof",compiler=compiler)
            self.assertEqual(result["status"],"PASS")
            self.assertIn("#define _PIC_PHOTOLYTIC_REACTIONS_MODE_",(root/"proof/effective-macros.txt").read_text())

    def test_late_contradictory_on_is_rejected_despite_early_off(self):
        compiler=shutil.which("g++")
        if not compiler:self.skipTest("C++ preprocessor unavailable")
        with tempfile.TemporaryDirectory(prefix="m2-effective-control-") as tmp:
            root=Path(tmp);build=self.headers(root,"#undef _PIC_PHOTOLYTIC_REACTIONS_MODE_\n#define _PIC_PHOTOLYTIC_REACTIONS_MODE_ _PIC_PHOTOLYTIC_REACTIONS_MODE_ON_\n")
            with patch.object(builder,"REPO",root),self.assertRaisesRegex(RuntimeError,"effective M2"):
                builder.effective_configuration(build,root,root/"proof",compiler=compiler)
            self.assertIn("photolytic chemistry must be OFF",(root/"proof/stderr.log").read_text())

    def test_missing_macro_is_not_treated_as_preprocessor_zero(self):
        compiler=shutil.which("g++")
        if not compiler:self.skipTest("C++ preprocessor unavailable")
        with tempfile.TemporaryDirectory(prefix="m2-effective-control-") as tmp:
            root=Path(tmp);build=self.headers(root,"#undef _RND_MODE_\n#undef _RND_MODE_MERSENNE_TWISTER_\n")
            with patch.object(builder,"REPO",root),self.assertRaises(RuntimeError):
                builder.effective_configuration(build,root,root/"proof",compiler=compiler)

    def test_derived_m2_disables_both_controls_sampling_retains_both(self):
        source=builder.REPO/"input/moon.input"
        m2=builder.derive_compile_input(source,"protocol_fixture","m2")
        sampling=builder.derive_compile_input(source,"protocol_fixture","sampling")
        self.assertRegex(m2,r"define\s+_PIC_PHOTOLYTIC_REACTIONS_MODE_\s+_PIC_PHOTOLYTIC_REACTIONS_MODE_OFF_")
        self.assertRegex(m2,r"PhotolyticReactions\s*=\s*off")
        self.assertRegex(sampling,r"define\s+_PIC_PHOTOLYTIC_REACTIONS_MODE_\s+_PIC_PHOTOLYTIC_REACTIONS_MODE_ON_")
        self.assertRegex(sampling,r"PhotolyticReactions\s*=\s*on")

    def test_duplicate_explicit_macro_is_rejected(self):
        text=(builder.REPO/"input/moon.input").read_text()
        with tempfile.TemporaryDirectory(prefix="m2-derived-control-") as tmp:
            source=Path(tmp)/"protocol.input"
            source.write_text(text+"\n define _PIC_PHOTOLYTIC_REACTIONS_MODE_ _PIC_PHOTOLYTIC_REACTIONS_MODE_ON_\n")
            with self.assertRaisesRegex(ValueError,"expected exactly one explicit application"):
                builder.derive_compile_input(source,"protocol_fixture","m2")


class ClusterPolicyRouting(unittest.TestCase):
    def test_cluster_preflight_uses_self_contained_retained_mode(self):
        # This invokes the real preflight routing with deliberately missing
        # scientific proof. The result MUST remain SKIPPED. Only the verifier
        # call is intercepted; no fake predecessor/model result is installed.
        import run_m2_cluster as cluster
        sys.path.insert(0, str(TEST_ROOT/"data_processing"))
        import audit_m2_packages
        with tempfile.TemporaryDirectory(prefix="m2-routing-protocol-only-") as tmp:
            executable = Path(tmp)/"never-executed"; executable.write_text("protocol only")
            args = argparse.Namespace(execute=True, qualification_root=None,
                amps=executable, input=Path(tmp)/"absent.in",
                memory_limit_bytes=1, artifact_limit_bytes=1, host_free_floor_bytes=0,
                disk_free_floor_bytes=0, sites_file=None, forecast_file=None,
                normalizations_file=None, statistical_support_file=None,
                core_hours=300, mpi_ranks=8)
            with patch.object(cluster, "verify_retained_executable", return_value={"scope": "protocol-only"}) as verify, \
                 patch.object(audit_m2_packages, "inspect", return_value={"records": []}):
                result = cluster.preflight(args)
                self.assertEqual(result["status"], "SKIPPED")
                verify.assert_called_once_with(executable.resolve(),
                    require_current_generated_tree=False)

    def test_development_reuse_keeps_live_generated_tree_requirement(self):
        import run_m2_development as development
        with tempfile.TemporaryDirectory(prefix="m2-development-policy-protocol-") as tmp:
            root = Path(tmp)
            executable = root/"never-executed"; executable.write_text("protocol only")
            args = argparse.Namespace(output_dir=root/"campaign", amps=executable)
            # Stop at the actual verifier boundary. No binary, compiler, local
            # probe, dataset audit or restoration build may execute here.
            with patch.object(development, "command_log", return_value=0), \
                 patch.object(development, "verify_retained_executable",
                              side_effect=RuntimeError("protocol stop before native reuse")) as verify, \
                 patch.object(development, "run") as launch, \
                 contextlib.redirect_stdout(io.StringIO()):
                self.assertEqual(development.run_campaign(args), 2)
                launch.assert_not_called()
                self.assertEqual(verify.call_args.args, (executable.resolve(),))
                self.assertTrue(verify.call_args.kwargs.get("require_current_generated_tree", True))
            result = json.loads((args.output_dir/"development_summary.json").read_text())
            self.assertEqual(result["formal_m2_status"], "NOT QUALIFIED")
            self.assertEqual(result["supporting_counts"]["ERROR"], 1)


if __name__ == "__main__":
    unittest.main()
