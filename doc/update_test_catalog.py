#!/usr/bin/env python3
"""Refresh the self-contained manual's suite snapshot from the real registry.

This optional editorial action requires the surrounding AMPS source checkout.
Normal manual compilation does not run it or import the test harness.
Descriptions and counts come from the validated expanded manifest; no runtime
status or scientific qualification is inferred from registration.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
TEST = ROOT.parent / "src" / "test"


def escape(text):
    replacements = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%",
                    "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}"}
    return "".join(replacements.get(c, c) for c in str(text))


def render():
    sys.path.insert(0, str(TEST))
    from lib.manifest import load_manifest
    suites = load_manifest(TEST / "manifest.json", ROOT.parent, TEST)
    cases = sum(len(s["expected_cases"]) for s in suites)
    canonical = json.dumps(
        [{"id": s["id"], "cases": s["expected_cases"]} for s in suites],
        sort_keys=True).encode()
    digest = hashlib.sha256(canonical).hexdigest()
    lines = [
        "% Generated by update_test_catalog.py; edit the registry, not this table.",
        r"\chapter{Registered test-suite snapshot}\label{ch:suites}",
        "Edition snapshot: {} suites and {} individual cases.".format(len(suites), cases),
        "This table records ownership and intent, not execution status. "
        "Exact individual descriptions remain in "
        r"\path{src/test/TEST_CATALOG.md}.",
        r"\par Registry identity: \path{" + digest + "}.",
        r"\begin{longtable}{L{0.38\textwidth}L{0.51\textwidth}}",
        r"\caption{All registered core and application test owners.}\\",
        r"\toprule Suite / cases / isolation & Contract and runner\\\midrule\endfirsthead",
        r"\toprule Suite / cases / isolation & Contract and runner\\\midrule\endhead",
    ]
    for suite in suites:
        left = r"\path{" + suite["id"] + "}" + r"\newline " + str(len(suite["expected_cases"]))
        left += " cases; " + ("exclusive" if suite.get("exclusive") else "nonexclusive")
        right = escape(suite["description"]) + r"\newline\path{src/test/" + suite["runner"] + "}"
        lines.append(left + " & " + right + r"\\")
    lines += [r"\bottomrule", r"\end{longtable}", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "TestSuiteCatalog.tex"
    content = render()
    if args.check:
        if not output.is_file() or output.read_text() != content:
            sys.exit("ERROR: manual suite snapshot is stale; run doc/update_test_catalog.py")
        print("PASS manual suite snapshot matches the expanded registry")
    else:
        output.write_text(content)
        print("Wrote", output)
